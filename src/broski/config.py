"""Configuration management module for broski.

Loads environment variables, validates settings using Pydantic,
and provides type-safe access to application configuration.
"""

from functools import lru_cache
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, Field, SecretStr, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class AudioConfig(BaseModel):
    """Configuration for local audio capture, VAD, STT, and TTS."""

    sample_rate: int = Field(
        default=16000,
        description="Audio sampling rate in Hz (16000 Hz is required for Whisper, Silero, and openWakeWord).",
    )
    channels: int = Field(default=1, description="Audio channels (1 = mono).")
    input_device_index: int | None = Field(
        default=None, description="Index of microphone device. None selects system default."
    )
    output_device_index: int | None = Field(
        default=None, description="Index of speaker device. None selects system default."
    )

    # Wake word settings
    wake_word_model: str = Field(
        default="hey_jarvis",
        description="Wake word trigger model name or path to custom .onnx model.",
    )
    wake_word_threshold: float = Field(
        default=0.5, ge=0.0, le=1.0, description="Activation confidence threshold for wake word."
    )

    # Voice Activity Detection (VAD) settings
    vad_threshold: float = Field(
        default=0.5, ge=0.0, le=1.0, description="Probability threshold for detecting speech."
    )
    vad_silence_duration_ms: int = Field(
        default=600,
        ge=200,
        le=3000,
        description="Silence duration in milliseconds before concluding speech has ended.",
    )

    # Whisper Speech-to-Text settings
    whisper_model_size: str = Field(
        default="base.en",
        description="Whisper model size ('tiny.en', 'base.en', 'small.en', 'base', etc.).",
    )
    whisper_compute_type: Literal["int8", "float16", "float32"] = Field(
        default="int8",
        description="Quantization compute type for CTranslate2 (int8 is optimal for CPU).",
    )
    whisper_cpu_threads: int = Field(
        default=2,
        ge=1,
        le=8,
        description="Max CPU worker threads allocated to Whisper to avoid thermal throttling.",
    )

    # Piper Text-to-Speech settings
    piper_voice_name: str = Field(
        default="en_US-lessac-medium",
        description="Piper voice model name (downloaded from Piper voice repo).",
    )

    @field_validator("sample_rate")
    @classmethod
    def validate_sample_rate(cls, v: int) -> int:
        valid_rates = {8000, 16000, 22050, 44100, 48000}
        if v not in valid_rates:
            raise ValueError(f"Sample rate {v} is unsupported. Expected one of {valid_rates}.")
        return v


class BrainConfig(BaseModel):
    """Configuration for Cloud LLM (Gemini API) and conversational reasoning."""

    api_key: SecretStr | None = Field(
        default=None,
        description="Google Gemini API key. If omitted, cloud reasoning is disabled.",
    )
    model: str = Field(
        default="gemini-2.5-flash",
        description="Default Gemini model identifier for conversational and tool routing.",
    )
    temperature: float = Field(
        default=0.7, ge=0.0, le=2.0, description="Sampling temperature for creative responses."
    )
    max_output_tokens: int = Field(
        default=1024, ge=64, le=8192, description="Maximum tokens generated per response turn."
    )


class ObsidianConfig(BaseModel):
    """Configuration for Obsidian Local REST API plugin integration."""

    api_key: SecretStr | None = Field(
        default=None, description="Secret API key generated by the Obsidian Local REST API plugin."
    )
    host: str = Field(default="127.0.0.1", description="Host where Obsidian REST server runs.")
    port: int = Field(
        default=27124, ge=1, le=65535, description="Port used by the Obsidian REST plugin."
    )
    use_https: bool = Field(
        default=True, description="Whether to communicate via HTTPS (Obsidian default is True)."
    )

    @property
    def base_url(self) -> str:
        protocol = "https" if self.use_https else "http"
        return f"{protocol}://{self.host}:{self.port}"


class PathsConfig(BaseModel):
    """Configuration for storage paths and database files."""

    data_dir: Path = Field(
        default=Path("data"), description="Root directory for local state, DB, and model cache."
    )
    db_name: str = Field(default="broski.db", description="Filename for SQLite database.")

    @property
    def db_path(self) -> Path:
        return self.data_dir / self.db_name

    @property
    def models_dir(self) -> Path:
        return self.data_dir / "models"

    def ensure_directories(self) -> None:
        """Create storage directories if they do not exist."""
        self.data_dir.mkdir(parents=True, exist_ok=True)
        self.models_dir.mkdir(parents=True, exist_ok=True)


class SecurityConfig(BaseModel):
    """Configuration for tool execution security and confirmation gates."""

    require_confirmation_for_critical: bool = Field(
        default=True,
        description="Require explicit user confirmation for destructive or mutating tools.",
    )
    confirmation_timeout_seconds: int = Field(
        default=30,
        ge=5,
        le=300,
        description="Seconds to wait for confirmation before timing out and aborting.",
    )
    log_level: Literal["DEBUG", "INFO", "WARNING", "ERROR", "CRITICAL"] = Field(
        default="INFO", description="Logging verbosity level."
    )


class Settings(BaseSettings):
    """Root configuration class for broski.

    Populates values from environment variables and an optional .env file.
    Environment variables take precedence over .env file entries.
    """

    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
        case_sensitive=False,
    )

    # Top-level direct mappings for environment variables
    gemini_api_key: SecretStr | None = Field(default=None)
    gemini_model: str = Field(default="gemini-2.5-flash")
    gemini_temperature: float = Field(default=0.7)

    audio_sample_rate: int = Field(default=16000)
    audio_channels: int = Field(default=1)
    audio_input_device_index: int | None = Field(default=None)
    audio_output_device_index: int | None = Field(default=None)

    wake_word_model: str = Field(default="hey_jarvis")
    wake_word_threshold: float = Field(default=0.5)

    vad_threshold: float = Field(default=0.5)
    vad_silence_duration_ms: int = Field(default=600)

    whisper_model_size: str = Field(default="base.en")
    whisper_compute_type: Literal["int8", "float16", "float32"] = Field(default="int8")
    whisper_cpu_threads: int = Field(default=2)

    piper_voice_name: str = Field(default="en_US-lessac-medium")

    obsidian_api_key: SecretStr | None = Field(default=None)
    obsidian_host: str = Field(default="127.0.0.1")
    obsidian_port: int = Field(default=27124)
    obsidian_use_https: bool = Field(default=True)

    data_dir: Path = Field(default=Path("data"))
    db_name: str = Field(default="broski.db")

    require_confirmation_for_critical: bool = Field(default=True)
    confirmation_timeout_seconds: int = Field(default=30)
    log_level: Literal["DEBUG", "INFO", "WARNING", "ERROR", "CRITICAL"] = Field(default="INFO")

    @property
    def audio(self) -> AudioConfig:
        return AudioConfig(
            sample_rate=self.audio_sample_rate,
            channels=self.audio_channels,
            input_device_index=self.audio_input_device_index,
            output_device_index=self.audio_output_device_index,
            wake_word_model=self.wake_word_model,
            wake_word_threshold=self.wake_word_threshold,
            vad_threshold=self.vad_threshold,
            vad_silence_duration_ms=self.vad_silence_duration_ms,
            whisper_model_size=self.whisper_model_size,
            whisper_compute_type=self.whisper_compute_type,
            whisper_cpu_threads=self.whisper_cpu_threads,
            piper_voice_name=self.piper_voice_name,
        )

    @property
    def brain(self) -> BrainConfig:
        return BrainConfig(
            api_key=self.gemini_api_key,
            model=self.gemini_model,
            temperature=self.gemini_temperature,
        )

    @property
    def obsidian(self) -> ObsidianConfig:
        return ObsidianConfig(
            api_key=self.obsidian_api_key,
            host=self.obsidian_host,
            port=self.obsidian_port,
            use_https=self.obsidian_use_https,
        )

    @property
    def paths(self) -> PathsConfig:
        return PathsConfig(
            data_dir=self.data_dir,
            db_name=self.db_name,
        )

    @property
    def security(self) -> SecurityConfig:
        return SecurityConfig(
            require_confirmation_for_critical=self.require_confirmation_for_critical,
            confirmation_timeout_seconds=self.confirmation_timeout_seconds,
            log_level=self.log_level,
        )


@lru_cache(maxsize=1)
def get_settings() -> Settings:
    """Return a cached singleton instance of application settings."""
    settings = Settings()
    settings.paths.ensure_directories()
    return settings
